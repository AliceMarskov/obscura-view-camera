import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {chromium} from 'playwright-core'

const base=process.env.WORKBENCH_URL??'http://127.0.0.1:5173/'
const browser=await chromium.launch({channel:'msedge',args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const page=await browser.newPage({viewport:{width:1000,height:710},deviceScaleFactor:1})
const problems=[]
page.on('pageerror',error=>problems.push(error.message))
page.on('console',msg=>{if(msg.type()==='error')problems.push(msg.text())})
const btn=name=>page.getByRole('button',{name,exact:true})
const ready=()=>page.waitForFunction(()=>!document.querySelector('.loading-scene')&&document.querySelector('.exposure canvas')?.dataset.converged==='true',null,{timeout:300000})
const pixelString=locator=>locator.evaluate(c=>c.toDataURL())
try {
  await page.goto(base)
  await ready()
  const upright=btn('正像辅助')
  assert.equal(await upright.getAttribute('aria-pressed'),'false')
  assert.match(await page.locator('.exposure canvas').evaluate(c=>getComputedStyle(c).transform),/matrix\(-1, 0, 0, -1/)
  await upright.click();await page.reload();await ready()
  assert.equal(await upright.getAttribute('aria-pressed'),'true')
  await page.getByLabel('场景',{exact:true}).selectOption('still-life');await ready()
  await btn('2×').click();await btn('钉住测点 A').click()
  const pin=page.getByLabel('测点 A 实时毛玻璃')
  const donePin=()=>page.waitForFunction(()=>document.querySelector('.pinned-loupe canvas')?.dataset.samples==='48',null,{timeout:300000})
  await donePin()
  const before=await pixelString(pin)
  await page.getByLabel('放大取景区').press('ArrowRight')
  assert.equal(await pixelString(pin),before)
  await btn('选择俯仰').click()
  const tilt=page.getByRole('spinbutton',{name:'俯仰数值'})
  await tilt.fill('6.3');await tilt.press('Enter');await ready();await donePin()
  assert.notEqual(await pixelString(pin),before)
  await page.screenshot({path:'verification/dual-loupe.png'})
  await btn('峰值对焦').click();await btn('构图网格').click();await btn('旋转后背').click()
  assert.equal(await pin.count(),0)
  await btn('拍摄接触印样').click()
  const preview=page.getByLabel('带曝光铭文的全幅正像印样')
  await preview.waitFor({state:'visible',timeout:300000})
  assert.ok(await preview.evaluate(c=>c.width<c.height&&c.height>1200),'a portrait proof contains the full-resolution exposure')
  const color=await pixelString(preview)
  await btn('银盐黑白').click()
  const silver=await pixelString(preview)
  assert.notEqual(silver,color)
  assert.ok(await preview.evaluate(c=>{
    const p=c.getContext('2d').getImageData(c.width/2,c.height/2,50,50).data
    return Array.from({length:p.length/4},(_,i)=>p[i*4]===p[i*4+1]&&p[i*4+1]===p[i*4+2]).every(Boolean)
  }))
  await btn('铂金印相').click()
  const platinum=await pixelString(preview)
  assert.notEqual(silver,platinum)
  const downloading=page.waitForEvent('download')
  await btn('保存 PNG').click()
  const png=await downloading
  assert.equal(png.suggestedFilename(),'Obscura-4x5-Proof.png')
  assert.equal((await readFile(await png.path())).toString('base64'),platinum.split(',')[1])
  await page.screenshot({path:'verification/contact-proof.png'})
  await btn('关闭').click()
  await page.getByRole('combobox',{name:'观察视图',exact:true}).selectOption('side')
  await btn('景深').click()
  await page.getByLabel('景深示意图例').waitFor()
  await btn('实验手册').click()
  const sound=btn('机械声效')
  assert.equal(await sound.getAttribute('aria-pressed'),'false')
  await sound.click();assert.equal(await sound.getAttribute('aria-pressed'),'true')
  await sound.click();await btn('关闭').click()
  await page.setViewportSize({width:390,height:844})
  await btn('旋转后背').click();await btn('1×').click()
  await ready()
  const box=await page.locator('.exposure').boundingBox()
  assert.ok(box.width>=290&&box.height>=225)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390)
  assert.deepEqual(problems,[])
  console.log('PASS default inversion, stored orientation, independent optical pin, portrait proof, 3 print tones, PNG bytes, depth legend, sound and phone layout')
}finally{await browser.close()}
