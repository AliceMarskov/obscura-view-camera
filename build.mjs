import {build,context} from 'esbuild'
import {copyFile,cp,mkdir,readFile,readdir,unlink} from 'node:fs/promises'
import path from 'node:path'

const serve=process.argv.includes('--serve')
const directory=serve?'.preview':'dist'
const assetDir=path.resolve(directory,'assets')
const sharedChunk=/^shared-[A-Z2-7]{8}\.js$/
const signature='/* Generated by the Obscura build. */'
const options={
  entryPoints:{main:'src/main.tsx',calibration:'src/calibration.ts'},
  outdir:assetDir,entryNames:'[name]',chunkNames:'shared-[hash]',
  bundle:true,splitting:true,platform:'browser',format:'esm',target:'es2022',
  jsx:'automatic',minify:true,legalComments:'eof',logLevel:'info',
  define:{'process.env.NODE_ENV':'"production"'}
}

async function copyStatic() {
  await mkdir(directory,{recursive:true})
  await Promise.all(['index.html','calibration.html','public/aperture.svg','LICENSE','ASSETS.md'].map(file=>
    copyFile(file,path.join(directory,path.basename(file)))))
  await cp('public/scenery',path.join(directory,'scenery'),{recursive:true})
}

// Old bundles predate output signatures. Follow their generated ESM imports
// before writing the new entries so the first upgrade can retire those chunks.
async function previousChunks() {
  const owned=new Set(),queue=['main.js','calibration.js']
  for(const file of queue) {
    let source
    try {source=await readFile(path.join(assetDir,file),'utf8')}
    catch(error) {if(error.code==='ENOENT')continue;throw error}
    for(const match of source.matchAll(/(?:\bfrom\s*|\bimport\s*\(?\s*)["']\.\/(shared-[A-Z2-7]{8}\.js)["']/g)) {
      if(!owned.has(match[1])) {owned.add(match[1]);queue.push(match[1])}
    }
  }
  return owned
}

async function retireChunks(metafile,previous) {
  const emitted=new Set(Object.keys(metafile.outputs).map(file=>path.resolve(file)))
  for(const file of await readdir(assetDir,{withFileTypes:true})) {
    if(!file.isFile()||!sharedChunk.test(file.name))continue
    const target=path.join(assetDir,file.name)
    if(emitted.has(target))continue
    const owned=previous.has(file.name)||(await readFile(target,'utf8')).startsWith(signature)
    if(owned)await unlink(target)
  }
}

if(serve){
  await copyStatic()
  const ctx=await context(options)
  await ctx.watch()
  const server=await ctx.serve({servedir:directory,host:'127.0.0.1',port:5173})
  console.log('Optical workbench http://127.0.0.1:'+server.port+'/')
}else{
  const previous=await previousChunks()
  const {metafile}=await build({...options,metafile:true,banner:{js:signature}})
  await copyStatic()
  await retireChunks(metafile,previous)
}
